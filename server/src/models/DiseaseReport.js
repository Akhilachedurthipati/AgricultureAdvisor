import mongoose from 'mongoose';

const diseaseReportSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true
    },
    crop: {
      type: String,
      default: 'General Foliar'
    },
    imageUrl: {
      type: String,
      required: true
    },
    imageFileName: {
      type: String,
      required: true
    },
    imageMimeType: {
      type: String,
      default: 'image/jpeg'
    },
    imageSize: {
      type: Number,
      default: 0
    },
    detection: {
      crop: { type: String },
      diseaseName: { type: String, required: true },
      scientificName: { type: String },
      isHealthy: { type: Boolean, required: true },
      confidenceScore: { type: Number, required: true },
      severity: { 
        type: String, 
        enum: ['Healthy', 'Mild', 'Moderate', 'Severe', 'Unknown'],
        default: 'Unknown'
      },
      affectedAreaPercentage: { type: Number, default: 0 },
      affectedAreaEstimateNote: { type: String },
      symptoms: [{ type: String }],
      causes: [{ type: String }],
      prevention: [{ type: String }],
      treatment: [{ type: String }],
      treatmentBreakdown: {
        culturalPractices: [{ type: String }],
        organicBiocontrol: [{ type: String }],
        chemicalInterventions: [
          {
            chemicalName: { type: String },
            activeIngredient: { type: String },
            dosage: { type: String },
            applicationTiming: { type: String },
            waitingPeriodPHI: { type: String },
            safetyPrecautions: { type: String }
          }
        ]
      }
    },
    featuresExtracted: {
      healthyGreenRatio: { type: Number },
      necroticRatio: { type: Number },
      chloroticRatio: { type: Number },
      meanHue: { type: Number }
    },
    disclaimer: {
      type: String,
      default: 'This diagnosis is generated by Agriculture Advisor computer vision screening. Visual symptoms can sometimes overlap between nutritional deficiencies and fungal pathogens. Confirm diagnosis with an agricultural extension officer before applying scheduled chemical fungicides.'
    }
  },
  {
    timestamps: true
  }
);

const DiseaseReport = mongoose.model('DiseaseReport', diseaseReportSchema);
export default DiseaseReport;

